import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { PNG } from "pngjs";

export const CELL = 30;
export const COLUMNS = 32;

const SOURCE =
  "PokeAPI/sprites commit 6e7928dcbd547d50b5c644fe76e093e8da98ac3f (sprites/items/*.png)";

const HELP = `Pack item icons into one sprite sheet and its slot map.

Usage: node tools/sprites/src/item-icons.ts --source DIR --sheet FILE --map FILE

  --source DIR   Directory of <identifier>.png icons (${SOURCE}).
  --sheet FILE   Output RGBA PNG: ${CELL} × ${CELL}px cells, ${COLUMNS} columns, sorted identifiers.
  --map FILE     Output TypeScript module exporting the identifier -> slot map.
`;

export interface Rgba {
  width: number;
  height: number;
  data: Uint8Array;
}

export interface Sheet extends Rgba {
  slots: ReadonlyMap<string, number>;
}

// Centres an icon in one cell. Larger icons may only lose fully transparent margins;
// fully transparent pixels are zeroed (invisible) so the sheet compresses better.
export function fitCell(icon: Rgba, name: string): Uint8Array {
  const cell = new Uint8Array(CELL * CELL * 4);
  const dx = Math.floor((CELL - icon.width) / 2);
  const dy = Math.floor((CELL - icon.height) / 2);
  for (let y = 0; y < icon.height; y++) {
    for (let x = 0; x < icon.width; x++) {
      const from = (y * icon.width + x) * 4;
      if (icon.data[from + 3] === 0) continue;
      const cx = x + dx;
      const cy = y + dy;
      if (cx < 0 || cy < 0 || cx >= CELL || cy >= CELL)
        throw new Error(
          `${name}: ${icon.width} × ${icon.height}px has opaque pixels outside a ${CELL}px cell`,
        );
      cell.set(icon.data.subarray(from, from + 4), (cy * CELL + cx) * 4);
    }
  }
  return cell;
}

export function packIcons(icons: ReadonlyMap<string, Rgba>): Sheet {
  const identifiers = [...icons.keys()].sort();
  const width = COLUMNS * CELL;
  const height = Math.ceil(identifiers.length / COLUMNS) * CELL;
  const data = new Uint8Array(width * height * 4);
  const slots = new Map<string, number>();
  identifiers.forEach((identifier, slot) => {
    const cell = fitCell(icons.get(identifier)!, identifier);
    const left = (slot % COLUMNS) * CELL;
    const top = Math.floor(slot / COLUMNS) * CELL;
    for (let y = 0; y < CELL; y++)
      data.set(cell.subarray(y * CELL * 4, (y + 1) * CELL * 4), ((top + y) * width + left) * 4);
    slots.set(identifier, slot);
  });
  return { width, height, data, slots };
}

export function slotModule(slots: ReadonlyMap<string, number>): string {
  const entries = [...slots].map(
    ([identifier, slot]) =>
      `  ${/^[A-Za-z_$][\w$]*$/.test(identifier) ? identifier : JSON.stringify(identifier)}: ${slot},`,
  );
  return `// Generated by \`vp run sprites:item-icons\` from tools/sprites/item-icons; do not edit.
// Source: ${SOURCE}.
// Slots index static/item-icons/sheet.png: ${CELL} × ${CELL}px cells, ${COLUMNS} columns, sorted identifiers.
// Missing identifiers deliberately use the neutral ItemIcon placeholder.
export const itemIconColumns = ${COLUMNS};

export const itemIconSlots: Readonly<Record<string, number>> = {
${entries.join("\n")}
};
`;
}

export function main(args = process.argv.slice(2)): number {
  const { values } = parseArgs({
    args,
    strict: true,
    options: {
      source: { type: "string" },
      sheet: { type: "string" },
      map: { type: "string" },
      help: { type: "boolean", short: "h" },
    },
  });
  if (values.help || !values.source || !values.sheet || !values.map) {
    console.log(HELP);
    return values.help ? 0 : 1;
  }
  const icons = new Map<string, Rgba>();
  for (const file of readdirSync(values.source)) {
    if (!file.endsWith(".png")) continue;
    const identifier = file.slice(0, -4);
    if (!/^[a-z0-9-]+$/.test(identifier)) throw new Error(`Unexpected icon file name: ${file}`);
    icons.set(identifier, PNG.sync.read(readFileSync(join(values.source, file))));
  }
  const sheet = packIcons(icons);
  const png = new PNG({ width: sheet.width, height: sheet.height });
  png.data = Buffer.from(sheet.data.buffer, sheet.data.byteOffset, sheet.data.byteLength);
  // Unfiltered rows with default deflate measured ~40% smaller than pngjs defaults here.
  const encoded = PNG.sync.write(png, {
    colorType: 6,
    deflateLevel: 9,
    filterType: 0,
    deflateStrategy: 0,
  });
  writeFileSync(values.sheet, encoded);
  writeFileSync(values.map, slotModule(sheet.slots));
  console.log(`${sheet.slots.size} icons -> ${values.sheet} (${sheet.width} × ${sheet.height}px)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  process.exitCode = main();
